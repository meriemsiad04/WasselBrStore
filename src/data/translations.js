export const formatPrice = (price, lang) => {
  const locales = {
    en: 'en-DZ',
    fr: 'fr-DZ',
    ar: 'ar-DZ'
  };
  
  return new Intl.NumberFormat(locales[lang], {
    style: 'decimal',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0
  }).format(price);
};
